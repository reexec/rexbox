#!/usr/bin/env python3
"""XDK symbol identification and the HLE overrides of a title's generated code.

A title's recompilation pipeline (its own scripts/recomp/regenerate.py, which
runs the title's lifter) calls these. They work on plain data and know no
lifter: the function starts the title's disassembler found, and the lifter's
symbol names, come in as arguments.

    identify_symbols   runs rexbox_xdk_symbols (XbSymbolDatabase) on the XBE
                       and writes <out>/xdk_symbols.json
    write_hle_overrides
                       writes <out>/hle_overrides.c: for every function of a
                       library chosen for HLE, a definition of the function's
                       lifted symbol that enters the HLE through
                       rexbox_hle_enter (include/rexbox/recomp/recomp_hle_entry.h),
                       and the table of identified XDK variables

The title's recomp directory holds the inputs:
    hle_libraries.json       libraries/functions replaced by HLE exports, and
                             'lifted': functions of those libraries kept as lifted code
    xdk_symbols_extra.json   XDK functions XbSymbolDatabase misses
"""

import json
import pathlib
import subprocess
import sys


def find_symbol_tool(explicit, candidates):
    """rexbox_xdk_symbols: `explicit` when given, else the first candidate path that exists."""
    if explicit is not None:
        return pathlib.Path(explicit).resolve()
    for candidate in candidates:
        if pathlib.Path(candidate).is_file():
            return pathlib.Path(candidate)
    sys.exit("rexbox_xdk_symbols not found -- build it first "
             "(scripts/build_win32_x86.ps1 -Target rexbox_xdk_symbols) or pass --symbols-tool")


def identify_symbols(tool, xbe, out_dir, extra_symbols):
    """Runs `tool` on `xbe` into <out_dir>/xdk_symbols.json; returns the symbols plus the extra ones."""
    print("=== xdk symbols", flush=True)
    target = out_dir / "xdk_symbols.json"
    result = subprocess.run([str(tool), str(xbe), "--json", str(target)], capture_output=True, text=True)
    if result.returncode != 0:
        sys.exit(f"rexbox_xdk_symbols failed: {result.stderr.strip()}")
    symbols = json.loads(target.read_text(encoding="utf-8"))
    if extra_symbols is not None and extra_symbols.is_file():
        known = {int(s["address"], 16) for s in symbols}
        for extra in json.loads(extra_symbols.read_text(encoding="utf-8"))["symbols"]:
            if int(extra["address"], 16) not in known:
                symbols.append(dict(extra, call="unknown", params=0, build=0))
    print(f"    {len(symbols)} symbol(s)")
    return symbols


def write_hle_overrides(symbols, function_starts, out_dir, hle_libraries, entry_name, lifted_name):
    """One override per function of an HLE library that the disassembler found.

    `function_starts` is the set of guest addresses the title's lifter emits a
    function for. `entry_name(address)` is the lifter's symbol for the function
    at `address` (what the override defines), `lifted_name(address)` the name
    the lifter gives its own body when an override replaces it. Returns the
    path of the written file."""
    config = json.loads(hle_libraries.read_text(encoding="utf-8")) if hle_libraries.is_file() else {}
    libraries = set(config.get("libraries", []))
    single = {(f["library"], f["name"]) for f in config.get("functions", [])}
    # Functions of an HLE library the title keeps as lifted code: pure
    # internals a lifted caller needs (a title names them instead of running
    # with REXBOX_HLE_FALLBACK=lifted).
    lifted = set(config.get("lifted", []))
    chosen = {}
    skipped = []
    for symbol in symbols:
        if symbol["kind"] != "function":
            continue
        if symbol["library"] not in libraries and (symbol["library"], symbol["name"]) not in single:
            continue
        if symbol["name"] in lifted:
            continue
        address = int(symbol["address"], 16)
        if address not in function_starts:
            skipped.append(f"{symbol['library']} {symbol['name']} 0x{address:08X}")
            continue
        chosen.setdefault(address, symbol)  # first name wins for aliases

    lines = [
        "/* Generated by rexbox scripts/recomp/hle_overrides.py from xdk_symbols.json. Not committed.",
        " * Each function of an HLE library enters rexbox_hle_enter; the lifted body",
        " * stays available under the lifter's name for it. */",
        "",
        "#include \"rexbox/recomp/recomp_hle_entry.h\"",
        "",
    ]
    for address, symbol in sorted(chosen.items()):
        tag = f"{address:08X}"
        entry = entry_name(address)
        body = lifted_name(address)
        lines += [
            f"extern void {body}(void);",
            f"static RexboxHleSlot slot_{tag} = {{0x{tag}u, \"{symbol['library']}\", \"{symbol['name']}\", {body}, 0, 0}};",
            f"void {entry}(void)",
            "{",
            f"    rexbox_hle_enter(&slot_{tag});",
            "}",
            "",
        ]
    # Identified XDK variables, for HLE modules that receive their addresses
    # (XInput's device types are &g_DeviceType_*). Absolute-looking values below
    # the image are structure offsets the database reports as variables; they
    # are kept, the binding is by name.
    variables = sorted({(s["library"], s["name"], int(s["address"], 16))
                        for s in symbols if s["kind"] == "variable"}, key=lambda v: (v[2], v[1]))
    lines += [
        "const RexboxXdkVariable rexbox_xdk_variables[] = {",
    ] + [f"    {{\"{lib}\", \"{name}\", 0x{addr:08X}u}}," for lib, name, addr in variables] + [
        "    {0, 0, 0},",
        "};",
        "",
    ]
    missing = sorted(single - {(s["library"], s["name"]) for s in chosen.values()})
    for library, name in missing:
        skipped.append(f"{library} {name} (selected function not identified)")
    target = out_dir / "hle_overrides.c"
    target.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"    hle overrides: {len(chosen)} function(s) of {sorted(libraries)} and {len(single)} selected; "
          f"{len(skipped)} skipped; {len(lifted)} kept lifted; {len(variables)} XDK variable(s)")
    for item in skipped:
        print(f"      skipped {item}")
    return target
