"""hle_overrides.write_hle_overrides on a synthetic symbol list (no game data)."""

import json
import pathlib
import sys
import tempfile
import unittest

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from hle_overrides import write_hle_overrides  # noqa: E402


def symbol(library, name, address, kind="function"):
    return {"library": library, "name": name, "address": f"0x{address:08X}", "kind": kind}


class WriteHleOverrides(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.out = pathlib.Path(self.temp.name)
        self.config = self.out / "hle_libraries.json"
        self.config.write_text(json.dumps({
            "libraries": ["D3D8"],
            "functions": [{"library": "XAPILIB", "name": "XGetDevices"}, {"library": "XAPILIB", "name": "Missing"}],
            "lifted": ["D3D_Internal"],
        }), encoding="utf-8")

    def tearDown(self):
        self.temp.cleanup()

    def write(self, symbols, starts):
        return write_hle_overrides(symbols, starts, self.out, self.config,
                                   lambda a: f"fn_{a:08X}", lambda a: f"fn_{a:08X}_lifted")

    def test_overrides_and_variables(self):
        symbols = [
            symbol("D3D8", "Direct3D_CreateDevice", 0x10000),
            symbol("D3D8", "Direct3D_CreateDevice_Alias", 0x10000),
            symbol("D3D8", "D3D_Internal", 0x10010),          # kept lifted
            symbol("D3D8", "D3DDevice_NotFound", 0x10020),    # not a function start
            symbol("XAPILIB", "XGetDevices", 0x20000),        # selected by name
            symbol("XAPILIB", "XInputOpen", 0x20010),         # library not chosen
            symbol("XAPILIB", "g_DeviceType_Gamepad", 0x30000, kind="variable"),
        ]
        target = self.write(symbols, {0x10000, 0x10010, 0x20000, 0x20010})
        text = target.read_text(encoding="utf-8")
        self.assertIn('extern void fn_00010000_lifted(void);', text)
        self.assertIn('static RexboxHleSlot slot_00010000 = {0x00010000u, "D3D8", "Direct3D_CreateDevice", '
                      'fn_00010000_lifted, 0, 0};', text)
        self.assertIn("void fn_00010000(void)\n{\n    rexbox_hle_enter(&slot_00010000);\n}", text)
        self.assertNotIn("Alias", text)  # first name wins
        self.assertIn("void fn_00020000(void)", text)
        for absent in ("00010010", "00010020", "00020010"):
            self.assertNotIn(f"void fn_{absent}(void)", text)
        self.assertIn('    {"XAPILIB", "g_DeviceType_Gamepad", 0x00030000u},\n    {0, 0, 0},\n};', text)
        self.assertTrue(text.startswith("/* Generated by rexbox scripts/recomp/hle_overrides.py"))
        self.assertNotIn("\r", text)


if __name__ == "__main__":
    unittest.main()
